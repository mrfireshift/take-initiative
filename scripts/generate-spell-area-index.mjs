import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { AREA_PLACEABLE_SPELL_IDS } from "../src/areaSaveSpellRules.js";
import {
  getAreaSaveAutomation,
  getAreaSaveRuleChoices,
  getSpellCatalog,
  getSpellEffectChoices,
} from "../src/spells-srd.js";
import { getSpellSaveWorkflowChoiceOptions } from "../src/spellSaveWorkflowRules.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const SPELL_AREA_INDEX_OUTPUT = path.join(ROOT, "src", "spellAreaIndex.js");

const sameJson = (left, right) => JSON.stringify(left) === JSON.stringify(right);

// Every choice value getAreaSaveAutomation reacts to: area rule choices, effect choices and save workflow options.
// Any other value resolves like "" (asserted by test/spellAreaIndex.test.js).
export function areaSaveChoiceValues(spellId) {
  return Array.from(new Set([
    ...getAreaSaveRuleChoices(spellId),
    ...getSpellEffectChoices(spellId),
    ...getSpellSaveWorkflowChoiceOptions(spellId),
  ].map((choice) => String(choice?.value ?? "")).filter(Boolean))).sort();
}

export function buildSpellAreaIndex() {
  const catalog = getSpellCatalog();
  const byId = new Map(catalog.map((spell) => [spell.id, spell]));

  // The only catalog fields spellAreaCatalog.js reads: area and range.
  const geometry = {};
  for (const spellId of [...AREA_PLACEABLE_SPELL_IDS].sort()) {
    const spell = byId.get(spellId);
    if (!spell) continue;
    geometry[spellId] = {
      ...(spell.area !== undefined ? { area: spell.area } : {}),
      ...(spell.range !== undefined ? { range: spell.range } : {}),
    };
  }

  // getAreaSaveAutomation per spell: "" holds the default, the other keys only the choices that differ from it.
  const saveAutomation = {};
  for (const spellId of catalog.map((spell) => spell.id).sort()) {
    const base = getAreaSaveAutomation(spellId, "");
    const entry = base ? { "": base } : {};
    for (const choiceValue of areaSaveChoiceValues(spellId)) {
      const automation = getAreaSaveAutomation(spellId, choiceValue);
      if (!sameJson(automation, base)) entry[choiceValue] = automation;
    }
    if (Object.keys(entry).length) saveAutomation[spellId] = entry;
  }

  return { geometry, saveAutomation };
}

function objectLines(name, value) {
  return [
    `export const ${name} = Object.freeze({`,
    ...Object.keys(value).map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(value[key])},`),
    "});",
  ];
}

export function buildSpellAreaIndexSource() {
  const { geometry, saveAutomation } = buildSpellAreaIndex();
  return [
    "// Generated by scripts/generate-spell-area-index.mjs - DO NOT EDIT MANUALLY",
    "// The spell catalog data needed by spellAreaCatalog.js and by the zone save reminders, so that the popovers",
    "// importing them (turn notice, Quick HP, conditions, effects) do not load spells-srd.js.",
    "// Regenerate with `npm run generate:spell-area-index` after changing spells or their area/save rules.",
    "",
    ...objectLines("SPELL_AREA_GEOMETRY_BY_ID", geometry),
    "",
    ...objectLines("AREA_SAVE_AUTOMATION_BY_ID", saveAutomation),
    "",
    "// Same result as getAreaSaveAutomation(spellId, choiceValue) in spells-srd.js, as a fresh copy.",
    "export function lookupAreaSaveAutomation(spellId, choiceValue = \"\") {",
    "  const entry = AREA_SAVE_AUTOMATION_BY_ID[String(spellId || \"\")];",
    "  if (!entry) return null;",
    "  const key = Object.hasOwn(entry, choiceValue) ? choiceValue : \"\";",
    "  const automation = Object.hasOwn(entry, key) ? entry[key] : null;",
    "  return automation ? structuredClone(automation) : null;",
    "}",
    "",
  ].join("\n");
}

const isMain = process.argv[1]
  && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  const source = buildSpellAreaIndexSource();
  fs.writeFileSync(SPELL_AREA_INDEX_OUTPUT, source, "utf8");
  const { geometry, saveAutomation } = buildSpellAreaIndex();
  console.log(`Wrote ${Object.keys(geometry).length} area geometries and ${Object.keys(saveAutomation).length} save automations to ${path.relative(ROOT, SPELL_AREA_INDEX_OUTPUT)}`);
}
